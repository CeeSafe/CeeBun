"""Interior mutability in Bun's hand-written Rust: Cell/RefCell by element and by place, and the related types.
Same file selection as analysis/bun_rust_features.py (src/, no test dirs, no generated files); comment lines skipped."""
import collections, os, re, sys

ROOT = sys.argv[1]
SKIP = {".git", "node_modules", "target", "test", "tests"}
GEN = re.compile(r"@generated|DO NOT EDIT|auto-?generated|generated by", re.I)
INTS = {"u8", "u16", "u32", "u64", "u128", "usize", "i8", "i16", "i32", "i64", "i128", "isize", "f32", "f64"}


def arg_at(s, i):
    """s[i] is '<': return the text up to the matching '>'."""
    depth, j = 0, i
    while j < len(s):
        c = s[j]
        if c == "<":
            depth += 1
        elif c == ">" and s[j - 1] != "-":
            depth -= 1
            if depth == 0:
                return s[i + 1:j].strip()
        j += 1
    return None


def cell_kind(a):
    a = re.sub(r"^(core|std)::\w+::", "", a)
    if a == "bool":
        return "bool"
    if a in INTS:
        return "integer/float"
    if re.match(r"^(\*(const|mut)\s|NonNull<|&)", a):
        return "raw pointer / NonNull / reference"
    if re.match(r"^Option<\s*(\*(const|mut)|NonNull|&|ptr::NonNull|core::ptr::NonNull)", a):
        return "Option<pointer>"
    if a.startswith("Option<"):
        return "Option<other>"
    return "other"


def refcell_kind(a):
    a = re.sub(r"^(std::|core::|alloc::)?\w*::", "", a) if a.startswith(("std::", "core::")) else a
    if re.match(r"^(Vec|SmallVec|BabyList|VecDeque|ArrayVec|BoundedArray)\b", a):
        return "Vec-like"
    if re.search(r"(HashMap|HashSet|ArrayHashMap|BTreeMap|IndexMap|StringHashMap|AutoHashMap)\b", a.split("<")[0]):
        return "map/set"
    if a.startswith("Option<"):
        return "Option<...>"
    if re.match(r"^(String|Box<|MutableString)", a):
        return "String/Box"
    return "struct/other"


cell_el, ref_el = collections.Counter(), collections.Counter()
place = collections.Counter()
other = collections.Counter()
files_with = collections.Counter()
examples = collections.defaultdict(list)
RX = re.compile(r"\b(UnsafeCell|RefCell|Cell|SyncUnsafeCell)\s*<")
FIELD = re.compile(r"^\s*(pub(\([^)]*\))?\s+)?\w+\s*:\s*(\w+::)*(UnsafeCell|RefCell|Cell)\s*<")
STATIC = re.compile(r"^\s*(pub(\([^)]*\))?\s+)?static\s+(mut\s+)?\w+\s*:.*\b(UnsafeCell|RefCell|Cell)\s*<")
OTHER = {
    "OnceCell": r"\bOnceCell\s*(<|::)",
    "OnceLock": r"\bOnceLock\s*(<|::)",
    "LazyCell": r"\bLazyCell\s*(<|::)",
    "LazyLock": r"\bLazyLock\s*(<|::)",
    "thread_local! blocks": r"\bthread_local!\s*\{",
    "#[thread_local] statics": r"#\[thread_local\]",
    ".borrow_mut() calls": r"\.borrow_mut\(\)",
    ".borrow() calls": r"\.borrow\(\)",
    "Cell::new / RefCell::new / UnsafeCell::new": r"\b(Cell|RefCell|UnsafeCell)::new\b",
    "Rc<RefCell / Rc<Cell": r"\bRc<\s*(RefCell|Cell)\s*<",
    "Arc<..Cell": r"\bArc<\s*(RefCell|Cell|UnsafeCell)\s*<",
    "JsCell<": r"\bJsCell\s*<",
    "Mutex<": r"\bMutex\s*<",
    "Atomic* types": r"\bAtomic(Bool|U8|U16|U32|U64|Usize|I32|I64|Isize|Ptr)\b",
}
ORX = {k: re.compile(v) for k, v in OTHER.items()}
total_lines = 0
in_tl = 0
for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, "src")):
    dirnames[:] = [d for d in dirnames if d not in SKIP]
    for fn in filenames:
        if not fn.endswith(".rs"):
            continue
        path = os.path.join(dirpath, fn)
        rel = os.path.relpath(path, ROOT)
        text = open(path, errors="replace").read()
        if GEN.search(text[:2000]) or "/generated" in rel or rel.endswith("_generated.rs"):
            continue
        tl_depth = 0
        for ln, line in enumerate(text.splitlines(), 1):
            s = line.strip()
            if s.startswith("//"):
                continue
            total_lines += 1
            for k, rx in ORX.items():
                n = len(rx.findall(line))
                other[k] += n
            for m in RX.finditer(line):
                name = m.group(1)
                a = arg_at(line, m.end() - 1)
                if a is None:
                    a = "?"
                files_with[name] += 0
                if name == "Cell":
                    k = cell_kind(a)
                    cell_el[k] += 1
                    if len(examples["Cell " + k]) < 4:
                        examples["Cell " + k].append(f"{rel}:{ln}: {s[:110]}")
                elif name == "RefCell":
                    k = refcell_kind(a)
                    ref_el[k] += 1
                    if len(examples["RefCell " + k]) < 4:
                        examples["RefCell " + k].append(f"{rel}:{ln}: {s[:110]}")
                else:
                    other[name + " (type uses)"] += 1
                    if len(examples[name]) < 4:
                        examples[name].append(f"{rel}:{ln}: {s[:110]}")
                # place
                if tl_depth > 0 or "thread_local!" in line:
                    p = "thread_local!"
                elif STATIC.match(line):
                    p = "static"
                elif re.search(r"\b(Rc|Arc)<\s*(RefCell|Cell|UnsafeCell)", line):
                    p = "behind Rc/Arc"
                elif FIELD.match(line):
                    p = "struct field"
                else:
                    p = "other (signature, local, impl, alias, expression)"
                place[name + ": " + p] += 1
                if len(examples["place " + p]) < 3 and name != "UnsafeCell":
                    examples["place " + p].append(f"{rel}:{ln}: {s[:110]}")
            if "thread_local!" in line:
                tl_depth = max(0, line.count("{") - line.count("}"))
            elif tl_depth > 0:
                tl_depth = max(0, tl_depth + line.count("{") - line.count("}"))

print("hand-written non-comment lines scanned:", total_lines)
print("\nCell<T> by element:", sum(cell_el.values()))
for k, v in cell_el.most_common():
    print(f"  {v:>5}  {k}")
print("\nRefCell<T> by element:", sum(ref_el.values()))
for k, v in ref_el.most_common():
    print(f"  {v:>5}  {k}")
print("\nby place:")
for k, v in sorted(place.items()):
    print(f"  {v:>5}  {k}")
print("\nrelated:")
for k, v in other.items():
    print(f"  {v:>5}  {k}")
if len(sys.argv) > 2:
    print("\nexamples:")
    for k, v in examples.items():
        print(" ", k)
        for e in v:
            print("     ", e)
