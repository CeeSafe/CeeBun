"""Cell<T> whose element is plainly not Copy (owns a Box/Rc/Arc/RefPtr/Vec/String/Owned*), by the same file rules."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
ROOT = sys.argv[1]
SKIP = {".git", "node_modules", "target", "test", "tests"}
GEN = re.compile(r"@generated|DO NOT EDIT|auto-?generated|generated by", re.I)
RX = re.compile(r"\bCell\s*<")
NC = re.compile(r"\b(Box|Rc|Arc|RefPtr|Vec|String|Owned\w*|BunString|Strong|JSRef)\b")
n = nc = 0
ex = []
for d, ds, fs in os.walk(os.path.join(ROOT, "src")):
    ds[:] = [x for x in ds if x not in SKIP]
    for f in fs:
        if not f.endswith(".rs"): continue
        p = os.path.join(d, f); rel = os.path.relpath(p, ROOT)
        t = open(p, errors="replace").read()
        if GEN.search(t[:2000]) or "/generated" in rel or rel.endswith("_generated.rs"): continue
        for ln, line in enumerate(t.splitlines(), 1):
            if line.strip().startswith("//"): continue
            for m in RX.finditer(line):
                i = m.end() - 1; depth = 0; j = i
                while j < len(line):
                    if line[j] == "<": depth += 1
                    elif line[j] == ">" and line[j-1] != "-":
                        depth -= 1
                        if depth == 0: break
                    j += 1
                a = line[i+1:j]
                n += 1
                if NC.search(a):
                    nc += 1
                    if len(ex) < 5: ex.append(f"{rel}:{ln}: {line.strip()[:100]}")
print(n, "Cell<T>;", nc, "with a plainly non-Copy element")
print("\n".join(ex))
