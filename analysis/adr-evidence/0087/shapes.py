"""Shapes of a few macros in Bun's hand-written Rust (ADR 0087). Usage: python3 -I shapes.py <bun-upstream-root>.
Lines that start with `//` are skipped; otherwise raw text (no lexer), so counts are approximate."""
import collections, os, re, sys

ROOT = sys.argv[1]
SKIP = {".git", "node_modules", "target", "test", "tests"}
GEN = re.compile(r"@generated|DO NOT EDIT|auto-?generated|generated by", re.I)
texts = []
for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, "src")):
    dirnames[:] = [d for d in dirnames if d not in SKIP]
    for fn in filenames:
        if fn.endswith(".rs"):
            rel = os.path.relpath(os.path.join(dirpath, fn), ROOT)
            t = open(os.path.join(dirpath, fn), errors="replace").read()
            if GEN.search(t[:2000]) or "/generated" in rel or rel.endswith("_generated.rs"):
                continue
            texts.append((rel, "\n".join(l for l in t.splitlines() if not l.lstrip().startswith("//"))))


def calls(name):
    rx = re.compile(r"(?<![\w$])" + name + r"!\s*([\(\[\{])")
    for rel, t in texts:
        for m in rx.finditer(t):
            depth, i, close = 0, m.end() - 1, {"(": ")", "[": "]", "{": "}"}[m.group(1)]
            while i < len(t):
                if t[i] in "([{":
                    depth += 1
                elif t[i] in ")]}":
                    depth -= 1
                    if depth == 0:
                        break
                i += 1
            yield rel, t[m.end():i]


c = collections.Counter()
for _, a in calls("matches"):
    c["matches"] += 1
    if re.search(r"\bif\b", a): c["matches with guard"] += 1
    if "|" in a.replace("||", ""): c["matches with |"] += 1
print(dict(c))
c = collections.Counter()
for _, a in calls("vec"):
    c["vec"] += 1
    if re.search(r";\s*[\w.()]+\s*$", a.strip()): c["vec![x; n]"] += 1
    elif not a.strip(): c["vec![]"] += 1
print(dict(c))
c = collections.Counter()
for _, a in calls("format"):
    c["format"] += 1
    s = re.match(r'\s*"((?:[^"\\]|\\.)*)"', a)
    if s:
        specs = re.findall(r"\{[^{}]*\}", s.group(1).replace("{{", "").replace("}}", ""))
        if all(x in ("{}",) or re.fullmatch(r"\{\w+\}", x) for x in specs): c["only {} or {name}"] += 1
        if any(":" in x for x in specs): c["with :spec"] += 1
        if any("?" in x for x in specs): c["with Debug {:?}"] += 1
print(dict(c))
c = collections.Counter()
for _, a in calls("cfg"):
    c[re.sub(r"\s+", " ", a.strip())[:40]] += 1
print("cfg! top:", c.most_common(8))
attr = collections.Counter()
for rel, t in texts:
    for m in re.finditer(r"#\[cfg\(([^\]]*)\)\]", t):
        attr[re.sub(r"\s+", " ", m.group(1))[:40]] += 1
print("#[cfg] top:", attr.most_common(10), "total", sum(attr.values()))
dbg = sum(t.count("debug_assertions") for _, t in texts)
isdbg = sum(len(re.findall(r"\bIS_DEBUG\b", t)) for _, t in texts)
print("debug_assertions mentions", dbg, "IS_DEBUG mentions", isdbg)
c = collections.Counter()
for _, a in calls("write") :
    c["write"] += 1
for _, a in calls("comptime_string_map"):
    c["comptime_string_map"] += 1
print(dict(c))
print("Debug derive vs {:?} in format strings:",
      sum(len(re.findall(r"\{[\w.]*:#?\?\}", t)) for _, t in texts))
print("impl PartialEq / Hash / Clone / Default / Display / Debug by hand:",
      {k: sum(len(re.findall(r"\bimpl\b[^{;]*\b" + k + r"\b[^{;]*\bfor\b", t)) for _, t in texts)
       for k in ["PartialEq", "Hash", "Clone", "Default", "Display", "Debug", "Ord", "PartialOrd", "From"]})
