"""Macro census of Bun's hand-written Rust (ADR 0087).

Usage: python3 -I macro_census.py <bun-upstream-root> [section]

Walks src/ as analysis/bun_rust_features.py does (skips test dirs and generated files), strips comments and the
contents of string and char literals with a small lexer, then counts:
  - macro invocations `name!(`/`name![`/`name!{` (path-qualified names reduced to their last segment);
  - derives, per trait;
  - attributes, per first path;
  - `macro_rules!` definitions and the uses of each name;
  - debug_assert! arguments that may have side effects.
"""
import collections, os, re, sys

ROOT = sys.argv[1]
SECTION = sys.argv[2] if len(sys.argv) > 2 else "all"
SKIP = {".git", "node_modules", "target", "test", "tests"}
GEN = re.compile(r"@generated|DO NOT EDIT|auto-?generated|generated by", re.I)


def strip(src):
    """Comments removed; string literal contents replaced by nothing (quotes kept, `S` marks a string,
    `C` marks a c"..." literal); char literals become 'c'."""
    out = []
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if c == "/" and src.startswith("//", i):
            j = src.find("\n", i)
            i = n if j < 0 else j
            continue
        if c == "/" and src.startswith("/*", i):
            depth, i = 1, i + 2
            while i < n and depth:
                if src.startswith("/*", i):
                    depth += 1; i += 2
                elif src.startswith("*/", i):
                    depth -= 1; i += 2
                else:
                    i += 1
            continue
        # raw strings r"..", r#".."#, br#..#, cr#..#
        m = re.match(r'(b|c)?r(#*)"', src[i:i + 40])
        if m and (i == 0 or not (src[i - 1].isalnum() or src[i - 1] == "_")):
            hashes = m.group(2)
            end = src.find('"' + hashes, i + len(m.group(0)))
            out.append('C""' if m.group(1) == "c" else '""')
            i = n if end < 0 else end + 1 + len(hashes)
            continue
        if c == '"' or (c in "bc" and i + 1 < n and src[i + 1] == '"' and not (i and (src[i - 1].isalnum() or src[i - 1] == "_"))):
            kind = c if c != '"' else ""
            i += 1 if c == '"' else 2
            while i < n and src[i] != '"':
                i += 2 if src[i] == "\\" else 1
            i += 1
            out.append('C""' if kind == "c" else '""')
            continue
        if c == "'":
            m = re.match(r"'(\\u\{[0-9a-fA-F]+\}|\\x[0-9a-fA-F]{2}|\\.|[^\\'])'", src[i:i + 12])
            if m:
                out.append("'c'")
                i += len(m.group(0))
                continue
        out.append(c)
        i += 1
    return "".join(out)


def balanced(text, start):
    """text[start] is an opening bracket; return the inside."""
    pairs = {"(": ")", "[": "]", "{": "}"}
    stack, i = [], start
    while i < len(text):
        ch = text[i]
        if ch in pairs:
            stack.append(pairs[ch])
        elif stack and ch == stack[-1]:
            stack.pop()
            if not stack:
                return text[start + 1:i]
        i += 1
    return text[start + 1:]


INVOKE = re.compile(r"(?<![\w$])((?:[A-Za-z_]\w*::)*)([A-Za-z_]\w*)!\s*([\(\[\{])")
DERIVE = re.compile(r"#\[derive\(")
ATTR = re.compile(r"#!?\[\s*((?:[A-Za-z_]\w*::)*[A-Za-z_]\w*)")
RULES = re.compile(r"\bmacro_rules!\s*([A-Za-z_]\w*)")
SIDE = re.compile(r"(?<![=!<>])=(?![=>])|\+=|-=|\+\+|\.(pop|push|insert|remove|take|next|swap|replace|fetch_\w+|"
                  r"store|clear|drain|write\w*|read\w*|lock|unwrap)\(|&mut\b|\bunsafe\b")

files = []
for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, "src")):
    dirnames[:] = sorted(d for d in dirnames if d not in SKIP)
    for fn in sorted(filenames):
        if fn.endswith(".rs"):
            path = os.path.join(dirpath, fn)
            text = open(path, errors="replace").read()
            rel = os.path.relpath(path, ROOT)
            if GEN.search(text[:2000]) or "/generated" in rel or rel.endswith("_generated.rs"):
                continue
            files.append((rel, strip(text)))

inv = collections.Counter()
inv_files = collections.defaultdict(set)
derives = collections.Counter()
attrs = collections.Counter()
rules_defs = collections.Counter()
rules_where = collections.defaultdict(list)
c_literals = 0
dbg_total, dbg_side, dbg_examples = 0, 0, []
assert_side = 0
include_files = []
for rel, t in files:
    c_literals += t.count('C""')
    for m in RULES.finditer(t):
        rules_defs[m.group(1)] += 1
        rules_where[m.group(1)].append(rel)
    for m in INVOKE.finditer(t):
        name = m.group(2)
        if name == "macro_rules":
            continue
        inv[name] += 1
        inv_files[name].add(rel)
        if name in ("debug_assert", "debug_assert_eq", "debug_assert_ne", "assert", "assert_eq", "assert_ne"):
            arg = balanced(t, m.end() - 1)
            side = bool(SIDE.search(arg))
            if name.startswith("debug"):
                dbg_total += 1
                if side:
                    dbg_side += 1
                    if len(dbg_examples) < 400:
                        dbg_examples.append((rel, " ".join(arg.split())[:120]))
            elif side:
                assert_side += 1
        if name in ("include_bytes", "include_str"):
            include_files.append((rel, name, " ".join(balanced(t, m.end() - 1).split())[:100]))
    for m in DERIVE.finditer(t):
        for tr in balanced(t, m.end() - 1).split(","):
            tr = tr.strip().split("::")[-1]
            if tr:
                derives[tr] += 1
    for m in ATTR.finditer(t):
        attrs[m.group(1)] += 1

total_inv = sum(inv.values())
defined = set(rules_defs)
if SECTION in ("all", "summary"):
    print(f"files {len(files)}; invocations {total_inv:,}; distinct {len(inv):,}; macro_rules! definitions "
          f"{sum(rules_defs.values()):,} ({len(rules_defs)} names); c\"..\" literals {c_literals}")
    print(f"invocations of names defined by macro_rules! in Bun: {sum(v for k, v in inv.items() if k in defined):,}")
if SECTION in ("all", "top"):
    print("\nTOP 60 invocations (name count files defined-in-bun)")
    for k, v in inv.most_common(60):
        print(f"  {k:30} {v:>6} {len(inv_files[k]):>5} {'B' if k in defined else ''}")
if SECTION in ("all", "std"):
    STD = ["format", "write", "writeln", "print", "println", "eprint", "eprintln", "format_args", "vec", "assert",
           "assert_eq", "assert_ne", "debug_assert", "debug_assert_eq", "debug_assert_ne", "matches", "unreachable",
           "panic", "todo", "unimplemented", "concat", "stringify", "include_bytes", "include_str", "include",
           "cfg", "env", "option_env", "offset_of", "size_of", "line", "file", "column", "module_path",
           "const_assert", "static_assert", "compile_error", "thread_local", "addr_of", "addr_of_mut", "debug_unreachable",
           "bitflags", "formatcp", "concatcp", "enum_map", "enum_set", "defer", "scopeguard", "asm", "dbg", "try",
           "write_str"]
    print("\nSTD and third-party")
    for k in STD:
        print(f"  {k:20} {inv[k]:>6} {len(inv_files[k]):>5}")
if SECTION in ("all", "derive"):
    print(f"\nDERIVES ({sum(derives.values()):,} trait mentions)")
    for k, v in derives.most_common(45):
        print(f"  {k:28} {v:>6}")
if SECTION in ("all", "attr"):
    print("\nATTRIBUTES (top 60)")
    for k, v in attrs.most_common(60):
        print(f"  {k:36} {v:>6}")
if SECTION in ("all", "rules"):
    used = sorted(((inv[k], k) for k in defined), reverse=True)
    print(f"\nBUN macro_rules! by use (top 50 of {len(defined)})")
    for v, k in used[:50]:
        print(f"  {k:32} uses {v:>6} defs {rules_defs[k]:>3} in {rules_where[k][0]}")
    print(f"  defined but never invoked: {sum(1 for k in defined if inv[k] == 0)}")
if SECTION in ("all", "dbg"):
    print(f"\ndebug_assert*: {dbg_total}; maybe side effects: {dbg_side}; assert* with: {assert_side}")
    for rel, a in dbg_examples[:400]:
        print(f"  {rel}: {a}")
if SECTION in ("all", "include"):
    print(f"\ninclude_bytes/include_str: {len(include_files)}")
    for x in include_files:
        print("  ", *x)
