"""Traits in Bun's first-party Rust: default methods, associated items, Self, generic methods, supertraits, iterators.
Same file walk as analysis/bun_rust_features.py (src/, skipping tests and generated files)."""
import collections, os, re, sys

ROOT = sys.argv[1]
SKIP = {".git", "node_modules", "target", "test", "tests"}
GEN = re.compile(r"@generated|DO NOT EDIT|auto-?generated|generated by", re.I)


def strip(text):
    # Remove comments, strings and char literals (keep lifetimes), preserving newlines.
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            i = j
        elif text.startswith("/*", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if text.startswith("/*", j): depth += 1; j += 2
                elif text.startswith("*/", j): depth -= 1; j += 2
                else: j += 1
            out.append("\n" * text.count("\n", i, j)); i = j
        elif c == 'r' and re.match(r'r#*"', text[i:i+10]) and (i == 0 or not (text[i-1].isalnum() or text[i-1] == '_')):
            m = re.match(r'r(#*)"', text[i:]); close = '"' + m.group(1)
            j = text.find(close, i + len(m.group(0)))
            j = n if j < 0 else j + len(close)
            out.append('""' + "\n" * text.count("\n", i, j)); i = j
        elif c == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == '\\' else 1
            out.append('""' + "\n" * text.count("\n", i, j)); i = j + 1
        elif c == "'":
            m = re.match(r"'(\\.[^']*|[^'\\])'", text[i:i+12])
            if m: out.append("' '"); i += len(m.group(0))
            else: out.append(c); i += 1
        else:
            out.append(c); i += 1
    return "".join(out)


def block(text, open_at):
    depth = 0
    for j in range(open_at, len(text)):
        if text[j] == '{': depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0: return j
    return len(text) - 1


def depth1_items(body):
    """Yield (kind, start, end, text) for items at depth 1 inside a {...} body (body excludes braces)."""
    i, n = 0, len(body)
    while i < n:
        m = re.compile(r"\b(fn|type|const)\b").search(body, i)
        if not m: return
        # depth check
        d = body.count('{', 0, m.start()) - body.count('}', 0, m.start())
        if d != 0:
            i = m.end(); continue
        # find end: first ';' or '{' at paren/angle depth 0 after m
        j, par = m.end(), 0
        while j < n:
            ch = body[j]
            if ch in '([': par += 1
            elif ch in ')]': par -= 1
            elif par == 0 and ch == ';':
                yield (m.group(1), m.start(), j, body[m.start():j + 1], False); i = j + 1; break
            elif par == 0 and ch == '{' and m.group(1) == 'fn':
                k = block(body, j)
                yield (m.group(1), m.start(), k, body[m.start():k + 1], True); i = k + 1; break
            elif par == 0 and ch == '{':
                k = block(body, j); j = k
            j += 1
        else:
            return


files = []
for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, "src")):
    dirnames[:] = [d for d in dirnames if d not in SKIP]
    for fn in filenames:
        if fn.endswith(".rs"):
            path = os.path.join(dirpath, fn); rel = os.path.relpath(path, ROOT)
            raw = open(path, errors="replace").read()
            if GEN.search(raw[:2000]) or "/generated" in rel or rel.endswith("_generated.rs"):
                continue
            files.append((rel, raw))

C = collections.Counter()
examples = collections.defaultdict(list)
adapters = collections.Counter()
TRAIT = re.compile(r"^[ \t]*(?:pub(?:\([^)]*\))?\s+)?(?:unsafe\s+)?trait\s+(\w+)([^{;]*)\{", re.M)
IMPL_FOR = re.compile(r"^[ \t]*(?:unsafe\s+)?impl\b([^{;]*)\bfor\b([^{;]*)\{", re.M)
ADAPT = set("map filter filter_map flat_map flatten enumerate zip chain take skip take_while skip_while rev peekable "
            "cloned copied any all find position count sum max min max_by_key min_by_key fold for_each collect last "
            "nth step_by map_while inspect scan partition product cmp eq by_ref find_map".split())
SRC = re.compile(r"\.(iter|iter_mut|into_iter|chars|bytes|char_indices|lines|split|split_whitespace|windows|chunks|"
                 r"chunks_exact|keys|values|values_mut|drain|split_terminator|rsplit|splitn|matches)\(\)?")
traits_with_default = 0
pertrait = []
for rel, raw in files:
    t = strip(raw)
    line_of = lambda pos: t.count("\n", 0, pos) + 1
    for m in TRAIT.finditer(t):
        name, head = m.group(1), m.group(2)
        C["traits"] += 1
        open_at = m.end() - 1; close = block(t, open_at); body = t[open_at + 1:close]
        sup = re.sub(r"\bwhere\b.*", "", head, flags=re.S)
        sup = re.sub(r"^\s*<.*?>", "", sup, flags=re.S)
        if re.match(r"\s*:", sup):
            C["traits with supertraits"] += 1
            if len(examples["super"]) < 6: examples["super"].append(f"{rel}:{line_of(m.start())} trait {name}{head.strip()}")
        if re.match(r"\s*<", head): C["generic traits (trait T<..>)"] += 1
        req, dflt, types, consts = [], [], 0, 0
        for kind, s, e, txt, has_body in depth1_items(body):
            if kind == 'fn':
                mm = re.match(r"fn\s+(\w+)", txt)
                if not mm: continue
                fname = mm.group(1)
                (dflt if has_body else req).append((fname, txt))
                if re.match(r"fn\s+\w+\s*<\s*(?!')", txt) or re.search(r"\bimpl\s+[A-Z]", txt.split('{')[0]):
                    C["generic methods in traits"] += 1
                    if len(examples["genm"]) < 6: examples["genm"].append(f"{rel}:{line_of(open_at+1+s)} {txt.split(chr(10))[0].strip()[:110]}")
                sig = txt.split('{')[0] if has_body else txt
                if re.search(r"\bSelf\b", sig):
                    C["trait methods naming Self in the signature"] += 1
                    if re.search(r"->\s*(Self|Option<Self>|Result<Self)", sig): C["  of which return Self/Option<Self>/Result<Self,_>"] += 1
                    if re.search(r"Self::\w+", sig): C["  of which name Self::Assoc"] += 1
                if not re.search(r"\(\s*(&\s*('\w+\s+)?(mut\s+)?)?(mut\s+)?self\b", sig): C["trait fns without self (static)"] += 1
                if re.search(r"\(\s*(mut\s+)?self\b", sig): C["trait fns taking self by value"] += 1
            elif kind == 'type':
                types += 1
                if len(examples["type"]) < 8: examples["type"].append(f"{rel}:{line_of(open_at+1+s)} {name}: {txt.strip()[:90]}")
                if '=' in txt: C["associated types with a default"] += 1
                if re.match(r"type\s+\w+\s*:", txt): C["associated types with bounds"] += 1
                if re.match(r"type\s+\w+\s*<", txt): C["generic associated types (GAT)"] += 1
            else:
                consts += 1
                if '=' in txt: C["associated consts with a default"] += 1
                if len(examples["const"]) < 6: examples["const"].append(f"{rel}:{line_of(open_at+1+s)} {name}: {txt.strip()[:90]}")
        C["required methods"] += len(req); C["default methods"] += len(dflt)
        C["associated types"] += types; C["associated consts"] += consts
        if types: C["traits with associated types"] += 1
        if consts: C["traits with associated consts"] += 1
        if dflt:
            traits_with_default += 1
            reqnames = {r[0] for r in req}
            calls = 0
            for fname, txt in dflt:
                b = txt[txt.find('{'):]
                if any(re.search(r"\bself\s*\.\s*" + r + r"\s*\(|Self::" + r + r"\s*\(", b) for r in reqnames):
                    C["defaults calling a required method"] += 1; calls += 1
                    if len(examples["dcall"]) < 12: examples["dcall"].append(f"{rel}:{line_of(m.start())} {name}::{fname}")
                if re.search(r"\bSelf\b", b): C["defaults using Self in the body"] += 1
                if re.search(r"Self::[A-Z]\w*", b) and not re.search(r"Self::[A-Z]\w*\s*\(", b): C["defaults reading Self::CONST/Type"] += 1
                if not reqnames: C["defaults in traits with no required fn"] += 1
            pertrait.append((len(dflt), len(req), f"{rel}:{line_of(m.start())} {name}"))
            if len(examples["dflt"]) < 10:
                examples["dflt"].append(f"{rel}:{line_of(m.start())} trait {name}: {len(req)} required, {len(dflt)} default ({', '.join(f for f,_ in dflt[:4])})")
        if not req and not types and not consts and not dflt: C["marker traits (empty)"] += 1
        if re.search(r"\bSelf\b", body): C["traits whose body names Self"] += 1
    for m in IMPL_FOR.finditer(t):
        C["impl ... for"] += 1
        open_at = m.end() - 1; close = block(t, open_at); body = t[open_at + 1:close]
        tr = m.group(1).strip()
        if re.search(r"\bSelf\b", body): C["impls whose body names Self"] += 1
        if re.search(r"^\s*type\s+\w+", body, re.M): C["impls defining an associated type"] += 1
        trn = re.sub(r"^<.*?>\s*", "", tr, flags=re.S)
        base = re.match(r"(?:\w+::)*(\w+)", trn)
        if base:
            C["impl of " + base.group(1)] += 1
            if base.group(1) in ("Iterator", "IntoIterator", "DoubleEndedIterator", "ExactSizeIterator", "FusedIterator") and len(examples[base.group(1)]) < 5:
                examples[base.group(1)].append(f"{rel}:{line_of(m.start())} impl{tr} for {m.group(2).strip()}")
    for m in re.finditer(r"->\s*impl\s+(?:\w+::)*(Iterator|IntoIterator|DoubleEndedIterator)\b", t):
        C["fns returning impl Iterator"] += 1
        if len(examples["retiter"]) < 5: examples["retiter"].append(f"{rel}:{line_of(m.start())}")
    for m in re.finditer(r"\b(dyn|impl)\s+(?:\w+::)*Iterator\b", t): C[m.group(1) + " Iterator (any position)"] += 1
    for m in re.finditer(r"[:,<+]\s*(?:\w+::)*(Iterator|IntoIterator)\s*<", t): C["Iterator/IntoIterator as a bound"] += 1
    C["Self:: projections"] += len(re.findall(r"\bSelf::[A-Z]\w*", t))
    C["T::Assoc / <T as Tr>::Assoc projections"] += len(re.findall(r"(?<![\w:])(?!Self\b)[A-Z]\w?::(Output|Item|Error|Target|Ok|Value|Key|Elem|Inner)\b", t)) + len(re.findall(r"<\s*\w+\s+as\s+[\w:<>]+\s*>::\w+", t))
    # adapter chains starting at an iterator source
    for m in SRC.finditer(t):
        C["iterator sources (.iter()/.chars()/...)"] += 1
        j, chain = m.end(), []
        if not t[m.start():m.end()].endswith("()"):
            if t[j - 1] != "(":
                continue
            d = 1
            while j < len(t) and d:
                if t[j] == "(": d += 1
                elif t[j] == ")": d -= 1
                j += 1
        # follow .name( ... ) calls with balanced parens
        while True:
            k = re.match(r"\s*\.\s*(\w+)\s*(::<[^>]*>)?\s*\(", t[j:])
            if not k: break
            chain.append(k.group(1)); p = j + k.end(); d = 1
            while p < len(t) and d:
                if t[p] == '(': d += 1
                elif t[p] == ')': d -= 1
                p += 1
            j = p
        ad = [c for c in chain if c in ADAPT]
        if ad:
            C["adapter chains"] += 1
            if len(ad) >= 3: C["adapter chains of 3+ adapters"] += 1
            for a in set(ad): adapters[a] += 1
            if len(ad) >= 3 and len(examples["chain"]) < 6:
                examples["chain"].append(f"{rel}:{line_of(m.start())} .{m.group(1)}()" + "".join("." + c + "()" for c in chain))
        else:
            C["sources used in for/without adapters"] += 1

C["traits with default methods"] = traits_with_default
print(f"files: {len(files)}")
for k in sorted(C, key=lambda k: (not k.startswith("impl of"), k)):
    if k.startswith("impl of") and C[k] < 25: continue
    print(f"{C[k]:>7}  {k}")
print("adapters (chains using each):")
for a, n in adapters.most_common(): print(f"{n:>7}  {a}")
for k, v in examples.items():
    print(f"-- {k}")
    for e in v: print("   ", e)

pertrait.sort(reverse=True)
print("-- top traits by defaults")
for d, r, w in pertrait[:12]: print(f"   {d:>3} default {r:>3} required  {w}")
import statistics
